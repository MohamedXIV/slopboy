/**
 * Offline release manifest generated from the *real* Next.js static export.
 * Atomically caches the exact approved pages, scripts, styles and cartridges.
 * No runtime API, remote URLs or user-generated assets are cached.
 */
import {createHash} from 'node:crypto';
import {readdir,readFile,stat,writeFile} from 'node:fs/promises';
import {resolve,relative,sep} from 'node:path';
import {pathToFileURL} from 'node:url';
const ROOT=resolve(import.meta.dirname,'..','apps/web/out');
const EXTENSIONS=new Set(['.html','.js','.css','.json','.png','.svg','.ico','.webmanifest','.woff','.woff2','.slop','.txt']);
const MAX_OFFLINE_BYTES=48*1024*1024;
export function allowedPrecachePath(path:string):boolean {
  if(!path.startsWith('/')||path.includes('..')||/[?#]/.test(path))return false;
  if(path==='/sw.js')return false;
  const last=path.slice(path.lastIndexOf('/'));
  const dot=last.lastIndexOf('.');
  return dot>=0&&EXTENSIONS.has(last.slice(dot));
}
export function renderServiceWorker(paths:readonly string[],revision:string):string {
  if(!/^[a-f0-9]{16}$/.test(revision))throw Error('Invalid SW revision');
  const sorted=[...new Set(paths)].sort();
  if(!sorted.includes('/index.html')||!sorted.includes('/library.html'))throw Error('Required shell routes missing');
  if(sorted.some(path=>!allowedPrecachePath(path)))throw Error('Unapproved precache path');
  const urls=JSON.stringify(sorted);
  return `/* Generated by tools/build-offline.ts — do not modify manually. */
const CACHE='slopboy-static-${revision}';
const FILES=${urls};
self.addEventListener('install',event=>{
  event.waitUntil((async()=>{
    const cache=await caches.open(CACHE);
    await cache.addAll(FILES.map(path=>new Request(path,{credentials:'omit',cache:'reload'})));
    await self.skipWaiting();
  })());
});
self.addEventListener('activate',event=>{
  event.waitUntil((async()=>{
    const keys=await caches.keys();
    await Promise.all(keys.filter(k=>k.startsWith('slopboy-static-')&&k!==CACHE).map(k=>caches.delete(k)));
    await self.clients.claim();
  })());
});
self.addEventListener('fetch',event=>{
  const request=event.request;
  if(request.method!=='GET')return;
  const url=new URL(request.url);
  if(url.origin!==self.location.origin)return;
  if(request.mode==='navigate'){
    const pathname=url.pathname.endsWith('/')?url.pathname.slice(0,-1):url.pathname;
    const html=pathname==='/'?'/index.html':pathname+'.html';
    if(!FILES.includes(html))return;
    event.respondWith((async()=>{
      const cache=await caches.open(CACHE);
      return (await cache.match(html))||fetch(request);
    })());
    return;
  }
  if(!FILES.includes(url.pathname)||url.search)return;
  event.respondWith((async()=>{
    const cache=await caches.open(CACHE);
    return (await cache.match(url.pathname))||fetch(request);
  })());
});`;
}
export async function buildOffline(root=ROOT):Promise<{files:number;bytes:number;revision:string}> {
  const discovered:string[]=[];
  async function walk(folder:string):Promise<void>{
    for(const item of await readdir(folder,{withFileTypes:true})){
      const file=resolve(folder,item.name);
      if(item.isDirectory())await walk(file);
      else if(item.isFile()){
        const path='/'+relative(root,file).split(sep).join('/');
        if(allowedPrecachePath(path))discovered.push(path);
      }
    }
  }
  await walk(root);
  discovered.sort();
  let bytes=0;
  const hash=createHash('sha256');
  for(const path of discovered){
    const data=await readFile(resolve(root,path.slice(1)));
    bytes+=data.byteLength;
    if(bytes>MAX_OFFLINE_BYTES)throw Error('Offline bundle exceeds 48 MiB budget');
    hash.update(path);hash.update(data);
  }
  const revision=hash.digest('hex').slice(0,16);
  const worker=renderServiceWorker(discovered,revision);
  await writeFile(resolve(root,'sw.js'),worker);
  await writeFile(resolve(root,'offline-build.json'),JSON.stringify({revision,files:discovered.length,bytes},null,2)+'\n');
  return {files:discovered.length,bytes,revision};
}
if(process.argv[1] && import.meta.url===pathToFileURL(resolve(process.argv[1])).href){
  buildOffline().then(result=>console.log('Offline PWA cache:',result))
    .catch(error=>{console.error(error);process.exitCode=1;});
}
